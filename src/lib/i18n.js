// Persistent disclaimer footer — kept as a named export for anything importing it
// directly; also reachable via t('disclaimer').
export const DISCLAIMER = {
  en: translations.en.disclaimer,
  hi: translations.hi.disclaimer,
  mr: translations.mr.disclaimer,
}

function walk(obj, path) {
  return path.split('.').reduce((o, k) => (o == null ? undefined : o[k]), obj)
}

function interpolate(str, vars) {
  if (!vars || typeof str !== 'string') return str
  return str.replace(/\{(\w+)\}/g, (m, k) => (k in vars ? String(vars[k]) : m))
}

// translate(lang, 'a.b.c', { name }) — falls back to English, then to the key.
export function translate(lang, key, vars) {
  const val = walk(translations[lang], key) ?? walk(translations.en, key) ?? key
  return interpolate(val, vars)
}

// Hook bound to the current language.
export function useT() {
  const { lang } = useProfile()
  return (key, vars) => translate(lang, key, vars)
}

// Legacy dict-style helper (kept for any { en, hi, mr } object).
export function t(dict, lang) {
  return dict[lang] || dict.en
}
